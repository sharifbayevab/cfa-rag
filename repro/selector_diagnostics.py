"""Paired uncertainty, calibration, and feature ablations for the OOF selector."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from sklearn.metrics import average_precision_score, brier_score_loss, roc_auc_score
from sklearn.model_selection import GroupKFold

from selector_oof import gb, load_aligned, validate_split

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "outputs"


def write_macros(result):
    contrast = result["paired_question_bootstrap"]["all_nine_minus_ce_rank_length"]
    full = result["scores"]["all_nine"]
    macro = {
        "selDiagAUCDelta": f"{contrast['auc_difference']:.3f}",
        "selDiagAUCLo": f"{contrast['auc_ci95'][0]:.3f}",
        "selDiagAUCHi": f"{contrast['auc_ci95'][1]:.3f}",
        "selDiagAPDelta": f"{contrast['ap_difference']:.3f}",
        "selDiagAPLo": f"{contrast['ap_ci95'][0]:.3f}",
        "selDiagAPHi": f"{contrast['ap_ci95'][1]:.3f}",
        "selDiagBrier": f"{full['calibration']['brier']:.3f}",
        "selDiagECE": f"{full['calibration']['ece_10_equal_width']:.3f}",
    }
    (HERE.parent / "selectordiagmacros.tex").write_text(
        "% Generated by repro/selector_diagnostics.py\n"
        + "\n".join("\\newcommand{\\" + key + "}{" + value + "}" for key, value in macro.items())
        + "\n"
    )


def oof_predictions(X, y, groups, columns):
    out = np.full(len(y), np.nan)
    for train, test in GroupKFold(n_splits=5).split(X, y, groups):
        validate_split(groups, train, test)
        out[test] = gb().fit(X[train][:, columns], y[train]).predict_proba(X[test][:, columns])[:, 1]
    return out


def calibration(y, predictions, bins=10):
    edges = np.linspace(0, 1, bins + 1)
    table, ece = [], 0.0
    for i in range(bins):
        take = (predictions >= edges[i]) & (predictions < edges[i + 1] if i < bins - 1 else predictions <= edges[i + 1])
        if not take.any():
            continue
        confidence, prevalence, weight = predictions[take].mean(), y[take].mean(), take.mean()
        ece += weight * abs(confidence - prevalence)
        table.append({"low": float(edges[i]), "high": float(edges[i + 1]), "n": int(take.sum()),
                      "mean_prediction": float(confidence), "observed_rate": float(prevalence)})
    return {"brier": float(brier_score_loss(y, predictions)), "ece_10_equal_width": float(ece), "bins": table}


def paired_question_bootstrap(y, left, right, qids, datasets, n_boot=2000, seed=0):
    rng = np.random.default_rng(seed)
    unique = sorted(set(qids))
    by_dataset = {}
    indices = {}
    for group in unique:
        take = np.where(qids == group)[0]
        indices[group] = take
        by_dataset.setdefault(datasets[take[0]], []).append(group)
    auc, ap = [], []
    for _ in range(n_boot):
        blocks = []
        for groups in by_dataset.values():
            blocks.extend(indices[groups[i]] for i in rng.integers(0, len(groups), len(groups)))
        take = np.concatenate(blocks)
        auc.append(roc_auc_score(y[take], left[take]) - roc_auc_score(y[take], right[take]))
        ap.append(average_precision_score(y[take], left[take]) - average_precision_score(y[take], right[take]))
    return {
        "n_boot": n_boot,
        "auc_difference": float(roc_auc_score(y, left) - roc_auc_score(y, right)),
        "auc_ci95": [float(x) for x in np.percentile(auc, [2.5, 97.5])],
        "ap_difference": float(average_precision_score(y, left) - average_precision_score(y, right)),
        "ap_ci95": [float(x) for x in np.percentile(ap, [2.5, 97.5])],
    }


def main():
    X, y, datasets, generators, qids, passage_idx, names = load_aligned()
    all_columns = list(range(X.shape[1]))
    predictions = {
        "all_nine": oof_predictions(X, y, qids, all_columns),
        "ce_rank_length": oof_predictions(X, y, qids, [names.index("ce_rank"), names.index("length")]),
        "cross_encoder": X[:, names.index("ce")],
        "dense_relevance": X[:, names.index("rel")],
    }
    ablations = {}
    for omitted, name in enumerate(names):
        columns = [i for i in all_columns if i != omitted]
        p = oof_predictions(X, y, qids, columns)
        ablations[name] = {"auc": float(roc_auc_score(y, p)), "ap": float(average_precision_score(y, p))}
    scores = {}
    for name, p in predictions.items():
        scores[name] = {
            "auc": float(roc_auc_score(y, p)),
            "ap": float(average_precision_score(y, p)),
            "calibration": calibration(y, p) if name in {"all_nine", "ce_rank_length"} else None,
        }
    result = {
        "n_fragment_rows": len(y), "n_question_groups": len(set(qids)), "random_state": 0,
        "scores": scores, "leave_one_feature_out": ablations,
        "paired_question_bootstrap": {
            "all_nine_minus_ce_rank_length": paired_question_bootstrap(
                y, predictions["all_nine"], predictions["ce_rank_length"], qids, datasets),
            "all_nine_minus_cross_encoder": paired_question_bootstrap(
                y, predictions["all_nine"], predictions["cross_encoder"], qids, datasets, seed=1),
        },
    }
    OUTPUT.mkdir(exist_ok=True)
    (OUTPUT / "selector_diagnostics.json").write_text(json.dumps(result, indent=2) + "\n")
    write_macros(result)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
